-- البنية الأساسية
CREATE TABLE IF NOT EXISTS rows(col TEXT NOT NULL, id TEXT NOT NULL, data TEXT NOT NULL, ver INTEGER NOT NULL, seq INTEGER NOT NULL, deleted INTEGER NOT NULL DEFAULT 0, at TEXT, by TEXT, PRIMARY KEY(col,id));
CREATE INDEX IF NOT EXISTS rows_seq ON rows(seq);
CREATE TABLE IF NOT EXISTS auth(user_id TEXT PRIMARY KEY, email TEXT UNIQUE, salt TEXT, hash TEXT, fails INTEGER NOT NULL DEFAULT 0, locked_until INTEGER NOT NULL DEFAULT 0, must_change INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, user_id TEXT NOT NULL, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT, user_id TEXT, role TEXT, kind TEXT, col TEXT, row_id TEXT, ok INTEGER, detail TEXT);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT);
